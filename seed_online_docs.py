API = "http://127.0.0.1:8000"


def login(username, password):
    r = requests.post(f"{API}/api/v1/auth/login", json={"username": username, "password": password})
    r.raise_for_status()
    return r.json()["access_token"]


def create_online_doc(token, kb_id, title, html):
    r = requests.post(
        f"{API}/api/v1/kb/{kb_id}/online-documents",
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        json={"name": title, "content": html, "folder_path": "/"},
    )
    try:
        r.raise_for_status()
    except Exception as e:
        print(f"创建失败 {kb_id}/{title}: {r.status_code} {r.text}")
        raise
    return r.json()


def wrap_html(title, paragraphs):
    parts = [f"<h1>{title}</h1>"]
    for p in paragraphs:
        parts.append(f"<p>{p}</p>")
    return "\n".join(parts)


